const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("nimbo", {
  onHook: (fn) => ipcRenderer.on("hook", (_e, p) => fn(p)),
  onCursor: (fn) => ipcRenderer.on("cursor", (_e, p) => fn(p)),
  onMuted: (fn) => ipcRenderer.on("muted", (_e, m) => fn(m)),
  onPermission: (fn) => ipcRenderer.on("permission", (_e, p) => fn(p)),
  onPermissionDone: (fn) => ipcRenderer.on("permission-done", () => fn()),
  decide: (decision, rid) => ipcRenderer.send("decision", decision, rid),
  onMini: (fn) => ipcRenderer.on("mini", (_e, m) => fn(m)),
  toggleMini: () => ipcRenderer.send("toggle-mini"),
  chatOpen: (open) => ipcRenderer.send("chat-open", open),
  chatCmd: (action, value) => ipcRenderer.invoke("chat-cmd", action, value),
  village: () => ipcRenderer.send("village-show"),
  onTasks: (fn) => ipcRenderer.on("tasks", (_e, list) => fn(list)),
  taskDo: (action, h) => ipcRenderer.send("task-do", action, h), // focus · min · close de una ventana de la lista
  taskLaunch: (key) => ipcRenderer.send("task-launch", String(key)), // abrir un programa anclado que está cerrado
  taskMenu: (key) => ipcRenderer.send("task-menu", String(key)), // clic derecho: anclar / quitar / cerrar
  onWake: (fn) => ipcRenderer.on("wake", (_e, clip, meta) => fn(clip instanceof Uint8Array ? clip : null, { conf: Number(meta?.conf) || 0 })), // clip = el audio de la llamada (.wav)
  onWakeOn: (fn) => ipcRenderer.on("wake-on", (_e, on) => fn(on === true)), // ¿está escuchando «Oye Nimbo»?
  sayPhrase: (kind) => ipcRenderer.invoke("say-phrase", String(kind)), // audio (.wav) de una frase de aviso, o null
  onWakeWarm: (fn) => ipcRenderer.on("wake-warm", () => fn()),
  wakeLog: (kind, text, note) => ipcRenderer.send("wake-log", String(kind), String(text ?? ""), String(note ?? "")),
  wakeDone: () => ipcRenderer.send("wake-done"),
  liveDictation: (on) => ipcRenderer.send("live-dictation", on === true),
  onDictationPartial: (fn) => ipcRenderer.on("dictation-partial", (_e, text) => fn(text)),
  onQuickAsk: (fn) => ipcRenderer.on("quick-ask", () => fn()),
  ask: (msg) => ipcRenderer.invoke("ask", msg),
  dispatch: (id, prompt) => ipcRenderer.invoke("dispatch", id, prompt),
  onTheme: (fn) => ipcRenderer.on("theme", (_e, t) => fn(t)),
  onGithub: (fn) => ipcRenderer.on("github", (_e, list) => fn(list)),
  openGithub: () => ipcRenderer.send("open-github"),
  openUrl: (url) => ipcRenderer.send("open-url", url),
  setup: () => ipcRenderer.invoke("setup"),
  setupDo: (action, value) => ipcRenderer.invoke("setup-do", action, value),
  onSetupOpen: (fn) => ipcRenderer.on("setup-open", () => fn()),
  onName: (fn) => ipcRenderer.on("name", (_e, n) => fn(n)),
  onAnchor: (fn) => ipcRenderer.on("anchor", (_e, f) => fn(f)),
  onDock: (fn) => ipcRenderer.on("dock", (_e, edge) => fn(String(edge))), // top · bottom · left · right · float
  onDragSnap: (fn) => ipcRenderer.on("drag-snap", (_e, edge) => fn(String(edge))), // arrastrando: el borde donde se pegaría ("" = flotando)
  dragStart: (d) => ipcRenderer.send("drag-start", d),
  dragEnd: () => ipcRenderer.send("drag-end"),
  onDragAbort: (fn) => ipcRenderer.on("drag-abort", () => fn()),
  onWhatsapp: (fn) => ipcRenderer.on("whatsapp", (_e, d, alert) => fn(d, alert)),
  whatsappRefresh: () => ipcRenderer.send("whatsapp-refresh"),
  whatsappSummarize: () => ipcRenderer.send("whatsapp-summarize"), // al abrir la pestaña de WhatsApp: resume lo que falte
  whatsappDismiss: () => ipcRenderer.send("whatsapp-dismiss"),
  copy: (text) => ipcRenderer.send("copy", text),
  tts: (text) => ipcRenderer.invoke("tts", text),
  screenshot: () => ipcRenderer.invoke("screenshot"),
  plan: () => ipcRenderer.invoke("plan"),
  onPlan: (fn) => ipcRenderer.on("plan", (_e, p) => fn(p)),
  onVoice: (fn) => ipcRenderer.on("voice", (_e, on) => fn(on)),
  trello: () => ipcRenderer.invoke("trello"),
  onTrello: (fn) => ipcRenderer.on("trello", (_e, d) => fn(d)),
  onTrelloBusy: (fn) => ipcRenderer.on("trello-busy", (_e, b) => fn(b)),
  trelloRefresh: () => ipcRenderer.send("trello-refresh"),
  trelloBoard: (url) => ipcRenderer.send("trello-board", url),
  onTelegram: (fn) => ipcRenderer.on("telegram", (_e, s) => fn(s)),
  mail: () => ipcRenderer.invoke("mail"),
  onMail: (fn) => ipcRenderer.on("mail", (_e, d) => fn(d)),
  onMailBusy: (fn) => ipcRenderer.on("mail-busy", (_e, b) => fn(b)),
  onMailOpenUi: (fn) => ipcRenderer.on("mail-open-ui", () => fn()),
  mailRefresh: () => ipcRenderer.send("mail-refresh"),
  mailOpen: (id) => ipcRenderer.send("mail-open", id),
  delegateOpen: (d) => ipcRenderer.send("delegate-open", d),
  delegateRun: (d) => ipcRenderer.invoke("delegate-run", d),
  delegateShow: (file) => ipcRenderer.send("delegate-show", file),
  askCancel: () => ipcRenderer.send("ask-cancel"),
  onUpdate: (fn) => ipcRenderer.on("update", (_e, i) => fn(i)),
  onUpdateNone: (fn) => ipcRenderer.on("update-none", (_e, v) => fn(v)),
  onUpdateProgress: (fn) => ipcRenderer.on("update-progress", (_e, p) => fn(p)),
  onWhatsNew: (fn) => ipcRenderer.on("whatsnew", (_e, i) => fn(i)),
  updateInstall: () => ipcRenderer.invoke("update-install"),
  updateLater: () => ipcRenderer.send("update-later"),
  aiProviders: () => ipcRenderer.invoke("ai-providers"),
  aiSelect: (id) => ipcRenderer.send("ai-select", id),
  onAiError: (fn) => ipcRenderer.on("ai-error", (_e, m) => fn(m)),
  onAi: (fn) => ipcRenderer.on("ai", (_e, r) => fn(r)),
  interview: (req) => ipcRenderer.invoke("interview", req),
  spotifySearch: (query) => ipcRenderer.invoke("spotify-search", query),
  spotifyPlay: (uri) => ipcRenderer.invoke("spotify-play", uri),
  onSpotify: (fn) => ipcRenderer.on("spotify", (_e, ok) => fn(ok)),
  media: () => ipcRenderer.invoke("media"),
  onMedia: (fn) => ipcRenderer.on("media", (_e, m) => fn(m)),
  mediaDo: (order) => ipcRenderer.send("media-do", order), // "toggle" | "next" | "prev" | "seek:<segundos>" (media.js valida)
  mediaTime: () => ipcRenderer.invoke("media-time"),
  onMediaTime: (fn) => ipcRenderer.on("media-time", (_e, tm) => fn(tm)),
  lyrics: () => ipcRenderer.invoke("lyrics"), // { synced } | { plain } | null | { error }
  volumeGet: () => ipcRenderer.invoke("volume-get"), // 0–100, o -1 si no se puede
  volumeSet: (v) => ipcRenderer.invoke("volume-set", Math.round(Number(v))),
  reminders: () => ipcRenderer.invoke("reminders"),
  onReminders: (fn) => ipcRenderer.on("reminders", (_e, list) => fn(list)),
  onReminder: (fn) => ipcRenderer.on("reminder", (_e, r) => fn(r)),
  reminderDone: (id) => ipcRenderer.send("reminder-done", id),
  reminderSnooze: (id, min) => ipcRenderer.send("reminder-snooze", id, min),
  // Ruta real de un archivo soltado o elegido (las imágenes pegadas no tienen: devuelve "").
  filePath: (file) => webUtils.getPathForFile(file),
  hitRects: (rects) => ipcRenderer.send("hit-rects", rects),
  winHeight: (h) => ipcRenderer.send("win-height", h),
  onHover: (fn) => ipcRenderer.on("hover", (_e, on) => fn(on)),
  menu: () => ipcRenderer.send("menu"),
  openOptions: () => ipcRenderer.send("options-open"),
});
